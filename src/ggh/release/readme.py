"""OSS-02, OSS-06: the README results block, generated from the results bundle (D-20), and
the links block, generated from `ggh.release.links` (OWNER D-37).

`ggh readme-table` prints the results block; `--write FILE` replaces the text between each
pair of markers in FILE (`uv run ggh readme-table --write README.md`).
"""

from __future__ import annotations

from ggh.release import links
from ggh.release.card import (
    aim_dependent,
    aim_outcome,
    display,
    earlier_tables,
    evalkit_stamps,
    f3,
    iv,
    judges_of,
    outcome_table,
    scoring,
    shipped_bench,
    table,
)
from ggh.release.sources import Sources

START = "<!-- ggh:results:start (generated by `ggh readme-table`; do not edit) -->"
END = "<!-- ggh:results:end -->"
LINKS_START = "<!-- ggh:links:start (generated by `ggh readme-table`; do not edit) -->"
LINKS_END = "<!-- ggh:links:end -->"


class SpliceError(ValueError):
    pass


def results_table(src: Sources) -> str:
    main = src.main()
    judges = judges_of(main)
    header = ["Model", "Accuracy", *[f"Correct and grounded ({j})" for j in judges]]
    rows = [
        [
            f"**{m.model}**" if m.model == src.ft_model else m.model,
            iv(m.accuracy),
            *[iv(m.headline[j]) if j in m.headline else "–" for j in judges],
        ]
        for m in main.models
    ]
    return table(header, rows)


def _intro(src: Sources, n: int) -> list[str]:
    """The opening line and table(s). With one release, v1's block as it always was; with
    earlier releases in the bundle, the shipped run labelled with its extractor and judges,
    then each earlier release's published numbers under their own (never compared)."""
    main, b = src.main(), src.bundle
    if not src.earlier():
        return [
            f"On {n} expert-labelled PubMedQA questions (EvalKit run `{main.run_id}`, judges: "
            f"{b.judge_mode}, calibration: {b.shipped.calibration_status}); 95% intervals in "
            "square brackets:",
            "",
            results_table(src),
        ]
    ref = src.ref(main)
    return [
        f"{b.shipped.version} on {n} expert-labelled PubMedQA questions (EvalKit run "
        f"`{main.run_id}`, {scoring(ref)}, calibration of {b.shipped.version}: "
        f"{b.shipped.calibration_status}); every model in this table was scored in that run. "
        "95% intervals in square brackets:",
        "",
        outcome_table(src, ref, bold=src.ft_model),
        "",
        *earlier_tables(src, heading="#### "),
    ]


def results_block(src: Sources) -> str:
    main = src.main()
    b = src.bundle
    n = max((m.n for m in main.models), default=0)
    one = bool(src.earlier()) and len(src.ref(main).judges) == 1
    calibrated = "the judge calibrated" if one else "both judges calibrated"
    notes = [*evalkit_stamps(src), *disclosures(src)]
    caveats = "; ".join(notes) or calibrated
    bench = shipped_bench(src)
    p = b.parity
    parity = (
        "The local demo serves the benchmarked Q4_K_M GGUF (OWNER D-63); the published bf16 "
        f"weights agree with it on the label for {f3(p.label_agreement)} of {p.n} dev prompts."
        if p is not None
        else "The local demo serves the benchmarked Q4_K_M GGUF (OWNER D-63)."
    )
    lines = [
        START,
        *_intro(src, n),
        "",
        f"Caveats: {caveats}. {parity} On a laptop ({bench.chip}) the {bench.quant} GGUF "
        "generates "
        f"{bench.gen_tps_p50:.1f} tokens/s (p50). Research only, not medical advice.",
        END,
    ]
    return "\n".join(lines) + "\n"


def disclosures(src: Sources) -> list[str]:
    """The shipped release's calibration stamp per judge it relies on, as the bundle words it
    (OWNER D-59, D-60), who reviewed B5 and B8 (OWNER D-61) and the aim-rule caveat (OWNER
    D-62). Empty for a bundle without them (v1's block is unchanged)."""
    b, rel = src.bundle, src.bundle.shipped
    out = [c.wording for c in b.calibration if c.judge in rel.calibration_judges]
    if out and rel.calibration_status == "calibrated":
        out.append("EvalKit's own run summaries keep its per-run stamp (OWNER D-59)")
    own = set(rel.runs)
    who = sorted({r.reviewer for r in b.behaviour if r.run in own and r.reviewer})
    if who and src.earlier():
        names = " and ".join(dict.fromkeys(display(w) for w in who))
        out.append(f"B5 and B8 are a blind review by {names}, not the owner (OWNER D-61)")
    if aim_dependent(src):
        worse, held = aim_outcome(src)
        v = rel.version
        label = {r.model: r.version for r in src.earlier()}
        text = (
            f"{v}-vs-base citation results depend on how the judge applies the citation "
            "check's aim rule"
        )
        if worse:
            text += f"; a post-hoc count makes base better than {v} on {' and '.join(worse)}"
        text += f", so {v} is not claimed to beat base on citations"
        if held:
            names = " and ".join(f"{v}-vs-{label.get(m, m)}" for m in held)
            text += f", while {names} holds under both counts"
        out.append(text + " (OWNER D-62, `docs/measurements/aim_rule_check.json`)")
    return out


def links_block() -> str:
    lines = [LINKS_START]
    lines += [f"- {links.md(name)}" for name in links.LINKS]
    lines.append(LINKS_END)
    return "\n".join(lines) + "\n"


def splice(text: str, block: str, start: str = START, end: str = END) -> str:
    """Replace the block between the markers; refuse a file that lacks them."""
    if start not in text or end not in text:
        raise SpliceError(f"the file has no {start.split(' ')[1]} markers")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return head + block.rstrip("\n") + tail


def update(text: str, src: Sources) -> str:
    """Both generated blocks; the links block only where the file has its markers."""
    out = splice(text, results_block(src))
    if LINKS_START in out:
        out = splice(out, links_block(), LINKS_START, LINKS_END)
    return out
