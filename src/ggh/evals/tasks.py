"""EVK-07: the dev smoke and off-scope sets as EvalKit local JSONL tasks (Tech Spec §7.2).

Both task files copy everything but `name` and `dataset` from EvalKit's built-in `pubmedqa`
task, so a local case renders exactly the prompt the built-in task would render. They are
generated by `ggh tasks` and committed; a test regenerates them and compares.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import yaml
from evalkit.tasks import builtin_task

from ggh.data.build import OFFSCOPE_PATH, OUT_DIR, read_jsonl

LABELS = ("yes", "no", "maybe")
SEED = 7
N_SMOKE = 20
DEV_EVAL = OUT_DIR / "dev_eval.jsonl"
DATA = Path("data")
TASKS = Path("configs") / "tasks"
SMOKE_DATA = DATA / "dev_smoke.jsonl"
OFFSCOPE_DATA = DATA / "offscope_task.jsonl"
SMOKE_TASK = TASKS / "dev_smoke.yaml"
OFFSCOPE_TASK = TASKS / "offscope.yaml"


def _rank(pmid: str) -> str:
    return hashlib.sha256(f"{SEED}:smoke:{pmid}".encode()).hexdigest()


def dev_smoke_cases(root: Path) -> list[dict[str, Any]]:
    """20 seeded `dev_eval` rows (never used for selection, D-4), with their N1.2 prompt."""
    rows = sorted(read_jsonl(root / DEV_EVAL), key=lambda r: _rank(str(r["pmid"])))[:N_SMOKE]
    return [
        {
            "id": f"dev-{r['pmid']}",
            "question": r["question"],
            "context": list(r["sentences"]),
            "label": r["label"],
            "prompt": r["prompt"],
        }
        for r in rows
    ]


def offscope_cases(root: Path) -> list[dict[str, Any]]:
    return [
        {
            "id": r["id"],
            "question": r["question"],
            "context": list(r["sentences"]),
            "label": r["expected"]["label"],
            "prompt": r["prompt"],
        }
        for r in read_jsonl(root / OFFSCOPE_PATH)
    ]


def task_yaml(name: str, dataset: str, split: str) -> str:
    base = builtin_task("pubmedqa").model_dump(mode="json")
    base.update(name=name, dataset=dataset, split=split)
    return (
        "# Generated by `ggh tasks` from EvalKit's built-in pubmedqa task; do not edit.\n"
        + yaml.safe_dump(base, sort_keys=False, allow_unicode=False, width=100)
    )


def _jsonl(cases: list[dict[str, Any]]) -> str:
    keep = ("id", "question", "context", "label")
    return "".join(json.dumps({k: c[k] for k in keep}, ensure_ascii=True) + "\n" for c in cases)


def files(root: Path) -> dict[Path, str]:
    """Every generated file, keyed by its path under the repo root."""
    return {
        SMOKE_DATA: _jsonl(dev_smoke_cases(root)),
        OFFSCOPE_DATA: _jsonl(offscope_cases(root)),
        SMOKE_TASK: task_yaml("ggh_dev_smoke", "../../" + SMOKE_DATA.as_posix(), "dev_eval"),
        OFFSCOPE_TASK: task_yaml(
            "ggh_offscope", "../../" + OFFSCOPE_DATA.as_posix(), "offscope_eval"
        ),
    }


def write(root: Path) -> list[Path]:
    out = []
    for rel, text in files(root).items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        out.append(rel)
    return out


def prompts(root: Path, task_rel: Path) -> list[tuple[str, str]]:
    """(case id, prompt) for a committed task, loaded and rendered by EvalKit itself."""
    from evalkit.run import load_cases, load_task
    from evalkit.tasks import render_prompt

    task, base = load_task(str(root / task_rel))
    return [(c.id, render_prompt(task, c)) for c in load_cases(task, base)]
